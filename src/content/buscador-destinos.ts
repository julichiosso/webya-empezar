export const DESTINOS_BUSQUEDA: readonly DestinoBusqueda[] = DESTINOS_BASE.flatMap((d) => {
  const demo = DEMOS_BUSQUEDA.find((x) => x.de === d.id);
  return demo ? [d, { ...demo, palabras: d.palabras }] : [d];
});

/** /armar con el tipo (y el rubro, si se nombró) ya elegidos. Acá y no en home.ts: el buscador es cliente. */
export const hrefArmar = (tipo: string, rubro: string | null) =>
  rubro ? `/armar?tipo=${tipo}&rubro=${rubro}` : `/armar?tipo=${tipo}`;

